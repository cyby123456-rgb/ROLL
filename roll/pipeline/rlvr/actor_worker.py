import os
import json
import time

import numpy as np
import torch

from roll.distributed.scheduler.decorator import Dispatch, register
from roll.distributed.scheduler.protocol import DataProto
from roll.pipeline.base_worker import ActorWorker as BaseActorWorker
from roll.utils.dynamic_batching import get_dynamic_batching_loss_scale
from roll.utils.functionals import masked_mean, masked_sum, agg_loss, compute_approx_kl
from roll.utils.logging import get_logger

_ratio_log_logger = get_logger()


class ActorWorker(BaseActorWorker):

    @register(dispatch_mode=Dispatch.DP_MP_DISPATCH_FIRST)
    def train_step(self, data: DataProto):
        """Override train_step to collect train_infer_ratio data for batch-level dump."""
        # 仅在 config 中配置了 ratio_rollout_dump_dir 时才初始化 buffer
        dump_path = getattr(self.pipeline_config, "ratio_rollout_dump_dir", None)
        global_step = data.meta_info.get("global_step", 0)
        if dump_path:
            self._ratio_dump_buffer = []

        output = super().train_step(data)

        # Each train worker writes its own shard to avoid cross-rank JSON merge overhead.
        if dump_path and hasattr(self, '_ratio_dump_buffer') and self._ratio_dump_buffer:
            self._dump_ratio_buffer(dump_path, global_step, self._ratio_dump_buffer)
            self._ratio_dump_buffer = []

        return output

    def loss_func(self, data: DataProto, output_tensor: torch.Tensor):
        """
        loss func接口定义:
            data: DataProto, 由train_step透传
            output_tensor: torch.Tensor, model.forward()的输出Tensor
        """
        response_mask = data.batch["response_mask"][:, 1:].long()
        final_response_mask = data.batch.get("final_response_mask", response_mask)
        ref_log_probs = data.batch["ref_log_probs"]
        advantages = data.batch["advantages"]

        log_probs = self.strategy.op_compute_log_probs(
            logits=output_tensor, input_ids=data.batch["input_ids"], attention_mask=data.batch["response_mask"]
        )
        old_log_probs = self.get_old_log_probs_with_cache(data, log_probs)
        infer_log_probs = data.batch.get("infer_logprobs", old_log_probs)
        if infer_log_probs is None or infer_log_probs.numel() == 0:
            infer_log_probs = old_log_probs

        loss_scale = get_dynamic_batching_loss_scale(data, self.pipeline_config.loss_agg_mode) \
            if self.worker_config.use_dynamic_batching_in_train else None

        valid_samples = torch.any(final_response_mask > 0, dim=1).float()
        sample_weights = self.compute_sample_weights(data, response_mask)


        kl_loss = compute_approx_kl(
            log_probs=log_probs, log_probs_base=ref_log_probs, action_mask=final_response_mask, kl_penalty="k3"
        )
        kl_loss = agg_loss(loss_mat=kl_loss,
                        loss_mask=final_response_mask,
                        loss_agg_mode=self.pipeline_config.loss_agg_mode,
                        loss_scale=loss_scale)

        approxkl = compute_approx_kl(
            log_probs=log_probs, log_probs_base=old_log_probs, action_mask=response_mask, kl_penalty="mse"
        )
        policykl = compute_approx_kl(
            log_probs=log_probs, log_probs_base=old_log_probs, action_mask=response_mask, kl_penalty="kl"
        )

        train_infer_ratio = (old_log_probs - infer_log_probs).exp()
        train_infer_diff = old_log_probs.exp() - infer_log_probs.exp()
        # seq_geo: geometric mean over tokens, exp(mean(log π/π̄))
        train_infer_ratio_seq_geo = masked_mean(old_log_probs - infer_log_probs, response_mask, dim=-1).exp().unsqueeze(-1).expand_as(train_infer_ratio)
        # seq (sequence): product over tokens, exp(sum(log π/π̄))
        log_ratio_sum = masked_sum(old_log_probs - infer_log_probs, response_mask, dim=-1)
        train_infer_ratio_seq_values = log_ratio_sum.exp()
        train_infer_ratio_seq = train_infer_ratio_seq_values.unsqueeze(-1).expand_as(train_infer_ratio)
        train_infer_diff_seq = masked_mean(old_log_probs.exp() - infer_log_probs.exp(), response_mask, dim=-1).unsqueeze(-1).expand_as(train_infer_diff)

        # for metrics: seq_geo (geometric) and seq (sequence) both have per-sequence values
        train_infer_ratio_seq_geo_values = masked_mean(old_log_probs - infer_log_probs, response_mask, dim=-1).exp()
        train_infer_diff_seq_values = masked_mean(old_log_probs.exp() - infer_log_probs.exp(), response_mask, dim=-1)

        # PPL (Perplexity) metrics, adopt from verl(https://yingru.notion.site/When-Speed-Kills-Stability-Demystifying-RL-Collapse-from-the-Training-Inference-Mismatch-271211a558b7808d8b12d403fd15edda)
        # Formula: exp(-1/|T| * Σ log π_training(y_t|y_<t))
        # where |T| is the number of tokens generated by the model
        mean_log_prob_train = masked_mean(old_log_probs, response_mask, dim=-1)
        mean_log_prob_infer = masked_mean(infer_log_probs, response_mask, dim=-1)
        train_ppl = torch.exp(-mean_log_prob_train)
        infer_ppl = torch.exp(-mean_log_prob_infer)

        log_ppl_diff = mean_log_prob_infer - mean_log_prob_train
        # IMPORTANT: Compute per-sequence ratio first, then average
        # Note: log_ppl_diff = log(ppl_ratio), so ppl_ratio = exp(log_ppl_diff)
        # This is the inverse of geometric IS: ppl_ratio_i = 1 / geometric_is_i for each sequence
        ppl_ratio_per_seq = torch.exp(log_ppl_diff)

        # KL(infer||train) = log(infer_prob) - log(train_prob)
        infer_train_kl = infer_log_probs - old_log_probs

        # K3 estimator: KL ≈ r - log(r) - 1, where r = train_prob/infer_prob
        log_ratio_k3 = old_log_probs - infer_log_probs
        infer_train_k3_kl = torch.exp(log_ratio_k3) - log_ratio_k3 - 1

        # 计算 infer_train_ratio (π̄₂/π₂) = exp(infer_log_probs - old_log_probs)
        infer_train_ratio = (infer_log_probs - old_log_probs).exp()

        # 实现公式: Δ(π̄₂, π₂) = E_{q~D, y_i~d^{π̄₂}} [A^{π₂}(s, a)]
        # 其中 π̄₂ 对应 infer_log_probs，π₂ 对应 old_log_probs
        # 使用重要性采样: E_{π̄₂}[A^{π₂}] ≈ E_{π₂}[r * A^{π₂}]，其中 r = π̄₂/π₂
        # 如果数据来自 π̄₂，则直接计算: E_{π̄₂}[A^{π₂}] ≈ (1/N) Σ A^{π₂}(s_i, a_i)
        # 但为了更准确，我们使用重要性采样比率进行修正
        # delta_pi2_bar_pi2 = E_{π̄₂}[A^{π₂}]，使用重要性采样比率 r = π̄₂/π₂
        importance_ratio_bar_pi2_pi2 = infer_train_ratio  # r = π̄₂/π₂ = exp(infer_log_probs - old_log_probs)
        delta_pi2_bar_pi2 = importance_ratio_bar_pi2_pi2 * advantages  # r * A^{π₂}

        train_infer_ratio_mask_mean = 1.0
        train_infer_diff_mask_mean = 1.0
        train_infer_ratio_seq_geo_mask_mean = 1.0
        train_infer_ratio_seq_product_mask_mean = 1.0
        train_infer_diff_seq_mask_mean = 1.0
        train_infer_ratio_trunc_is_weight_mean = 1.0
        train_infer_ratio_trunc_is_weight_max = 1.0
        train_infer_ratio_trunc_is_weight_min = 1.0
        train_infer_ratio_trunc_is_weight = None
        train_infer_ratio_trunc_reverse_is_weight_mean = 1.0
        train_infer_ratio_trunc_reverse_is_weight_max = 1.0
        train_infer_ratio_trunc_reverse_is_weight_min = 1.0
        train_infer_ratio_trunc_reverse_is_weight = None

        # TODO 按照agentic的pipeline is修正方式进行调整
        if self.pipeline_config.train_infer_ratio_mask:
            train_infer_ratio_mask = (train_infer_ratio <= self.pipeline_config.train_infer_ratio_threshold_high).float() * (train_infer_ratio >= self.pipeline_config.train_infer_ratio_threshold_low).float()
            train_infer_ratio_mask_mean = masked_mean(train_infer_ratio_mask, final_response_mask, dim=-1).mean().detach().item()
            final_response_mask = final_response_mask * train_infer_ratio_mask
        if self.pipeline_config.train_infer_diff_mask:
            train_infer_diff_mask = (train_infer_diff <= self.pipeline_config.train_infer_diff_threshold_high).float() * (train_infer_diff >= self.pipeline_config.train_infer_diff_threshold_low).float()
            train_infer_diff_mask_mean = masked_mean(train_infer_diff_mask, final_response_mask, dim=-1).mean().detach().item()
            final_response_mask = final_response_mask * train_infer_diff_mask


        if self.pipeline_config.train_infer_ratio_seq_mask:
            # train_infer_ratio_seq_geo_mask = (train_infer_ratio_seq_geo <= self.pipeline_config.train_infer_ratio_seq_threshold_high).float() * (train_infer_ratio_seq_geo >= self.pipeline_config.train_infer_ratio_seq_threshold_low).float()
            # train_infer_ratio_seq_geo_mask_mean = masked_mean(train_infer_ratio_seq_geo_mask, final_response_mask, dim=-1).mean().detach().item()
            # final_response_mask = final_response_mask * train_infer_ratio_seq_geo_mask
            train_infer_ratio_seq_geo_mask = (
                (train_infer_ratio_seq_geo <= self.pipeline_config.train_infer_ratio_seq_threshold_high).float()
                * (train_infer_ratio_seq_geo >= self.pipeline_config.train_infer_ratio_seq_threshold_low).float()
            )
            train_infer_ratio_seq_geo_mask_mean = masked_mean(train_infer_ratio_seq_geo_mask, final_response_mask, dim=-1).mean().detach().item()
            final_response_mask = final_response_mask * train_infer_ratio_seq_geo_mask
        if getattr(self.pipeline_config, "train_infer_ratio_seq_product_mask", False):
            # mask by seq (product) ratio: exp(sum(log π/π̄)), 逐 token 广播的 per-seq 值
            train_infer_ratio_seq_product_mask = (
                (train_infer_ratio_seq <= self.pipeline_config.train_infer_ratio_seq_product_threshold_high).float()
                * (train_infer_ratio_seq >= self.pipeline_config.train_infer_ratio_seq_product_threshold_low).float()
            )
            train_infer_ratio_seq_product_mask_mean = masked_mean(train_infer_ratio_seq_product_mask, final_response_mask, dim=-1).mean().detach().item()
            final_response_mask = final_response_mask * train_infer_ratio_seq_product_mask
        if self.pipeline_config.train_infer_diff_seq_mask:
            train_infer_diff_seq_mask = (train_infer_diff_seq <= self.pipeline_config.train_infer_diff_seq_threshold_high).float() * (train_infer_diff_seq >= self.pipeline_config.train_infer_diff_seq_threshold_low).float()
            train_infer_diff_seq_mask_mean = masked_mean(train_infer_diff_seq_mask, final_response_mask, dim=-1).mean().detach().item()
            final_response_mask = final_response_mask * train_infer_diff_seq_mask

        # truncated IS on train/infer mismatch ratio: do not drop tokens, only reweight loss
        if getattr(self.pipeline_config, "train_infer_ratio_trunc_is", False):
            w = train_infer_ratio.clamp(
                self.pipeline_config.train_infer_ratio_trunc_is_low,
                self.pipeline_config.train_infer_ratio_trunc_is_high,
            )
            if getattr(self.pipeline_config, "train_infer_ratio_trunc_is_normalize", True):
                denom = masked_mean(w, final_response_mask, dim=-1).unsqueeze(-1)
                w = w / (denom + 1e-8)
            train_infer_ratio_trunc_is_weight = w
            train_infer_ratio_trunc_is_weight_mean = masked_mean(w, final_response_mask, dim=-1).mean().detach().item()
            train_infer_ratio_trunc_is_weight_max = torch.max(w * final_response_mask).detach().item()
            train_infer_ratio_trunc_is_weight_min = torch.min(
                w * final_response_mask + (1 - final_response_mask) * 1e10
            ).detach().item()

        # truncated reverse-IS on train/infer mismatch ratio: use infer/train ratio to reweight loss
        if getattr(self.pipeline_config, "train_infer_ratio_trunc_reverse_is", False):
            w_rev = infer_train_ratio.clamp(
                self.pipeline_config.train_infer_ratio_trunc_reverse_is_low,
                self.pipeline_config.train_infer_ratio_trunc_reverse_is_high,
            )
            if getattr(self.pipeline_config, "train_infer_ratio_trunc_reverse_is_normalize", True):
                denom_rev = masked_mean(w_rev, final_response_mask, dim=-1).unsqueeze(-1)
                w_rev = w_rev / (denom_rev + 1e-8)
            train_infer_ratio_trunc_reverse_is_weight = w_rev
            train_infer_ratio_trunc_reverse_is_weight_mean = masked_mean(
                w_rev, final_response_mask, dim=-1
            ).mean().detach().item()
            train_infer_ratio_trunc_reverse_is_weight_max = torch.max(
                w_rev * final_response_mask
            ).detach().item()
            train_infer_ratio_trunc_reverse_is_weight_min = torch.min(
                w_rev * final_response_mask + (1 - final_response_mask) * 1e10
            ).detach().item()

        # Select base log probs source used in importance sampling ratio.
        # mode:
        # - old: always old_log_probs
        # - infer: prefer infer_log_probs, fallback to old_log_probs
        # - auto: infer_log_probs only when update_validation is enabled
        update_validation_enabled = (
            hasattr(self.pipeline_config, 'update_validation')
            and self.pipeline_config.update_validation is not None
            and getattr(self.pipeline_config.update_validation, 'enable', False)
        )
        # Read from top-level config first. Keep update_validation fallback
        # only for backward compatibility with older configs.
        base_log_probs_mode = getattr(self.pipeline_config, "base_log_probs_mode", None)
        if base_log_probs_mode is None:
            base_log_probs_mode = "old"
            if hasattr(self.pipeline_config, "update_validation") and self.pipeline_config.update_validation is not None:
                base_log_probs_mode = getattr(self.pipeline_config.update_validation, "base_log_probs_mode", "old")

        if base_log_probs_mode == "infer":
            is_base_log_probs = infer_log_probs
        elif base_log_probs_mode == "auto":
            is_base_log_probs = (
                infer_log_probs if update_validation_enabled else old_log_probs
            )
        elif base_log_probs_mode == "old":
            is_base_log_probs = old_log_probs

        if self.pipeline_config.importance_sampling == "token":
            ratio = (log_probs - is_base_log_probs).exp()
        elif self.pipeline_config.importance_sampling == "seq":
            log_ratio = log_probs - is_base_log_probs
            masked_log_ratio = masked_mean(log_ratio, final_response_mask, dim=-1)
            ratio = masked_log_ratio.exp().unsqueeze(-1).expand_as(log_ratio)

        pg_clip_low = self.pipeline_config.pg_clip_low if self.pipeline_config.use_pg_clip_range else self.pipeline_config.pg_clip
        pg_clip_high = self.pipeline_config.pg_clip_high if self.pipeline_config.use_pg_clip_range else self.pipeline_config.pg_clip
        surr1 = ratio * advantages
        surr2 = ratio.clamp(1 - pg_clip_low, 1 + pg_clip_high) * advantages

        loss = -torch.min(surr1, surr2)

        if self.pipeline_config.dual_clip_loss:
            dual_clip_loss = -torch.max(-loss, (1 + self.pipeline_config.pg_clip * 2) * advantages)
            loss = torch.where(advantages < 0, dual_clip_loss, loss)

        is_correction_mode = getattr(self.pipeline_config, "is_correction", "default")
        if infer_log_probs is not None and is_correction_mode in ("vanilla", "reverse"):
            if is_correction_mode == "vanilla":
                correction_ratio = (old_log_probs - infer_log_probs).exp()
            else:
                correction_ratio = (infer_log_probs - old_log_probs).exp()
            loss = loss * correction_ratio


        if train_infer_ratio_trunc_is_weight is not None:
            loss = loss * train_infer_ratio_trunc_is_weight
        if train_infer_ratio_trunc_reverse_is_weight is not None:
            loss = loss * train_infer_ratio_trunc_reverse_is_weight

        if self.pipeline_config.use_rollout_importance_sampling_ratio:
            rollout_importance_sampling_clip = (train_infer_ratio > self.pipeline_config.rollout_importance_sampling_ratio_upper_bound).float()
            loss = train_infer_ratio.clamp(0, self.pipeline_config.rollout_importance_sampling_ratio_upper_bound) * loss

        # Optional IS correction on PPO loss:
        # - default: no-op
        # - vanilla: multiply by old_log_probs / infer_log_probs ratio
        # - reverse: multiply by inverse ratio


        weighted_pg_loss = agg_loss(loss_mat=loss, loss_mask=final_response_mask,
                                    loss_agg_mode=self.pipeline_config.loss_agg_mode,
                                    weights=sample_weights, loss_scale=loss_scale)
        original_pg_loss = agg_loss(loss_mat=loss, loss_mask=final_response_mask,
                                    loss_agg_mode=self.pipeline_config.loss_agg_mode,
                                    loss_scale=loss_scale)

        clipped_low = (ratio < 1 - pg_clip_low).float()
        clipped_high = (ratio > 1 + pg_clip_high).float()
        clipped = (clipped_low + clipped_high).float()

        mismatch_forward_kl_loss = None
        mismatch_reverse_kl_loss = None
        mismatch_forward_kl_value = 0.0
        mismatch_reverse_kl_value = 0.0

        if self.pipeline_config.use_kl_loss:
            total_loss = weighted_pg_loss + kl_loss * self.pipeline_config.kl_loss_coef
        else:
            total_loss = weighted_pg_loss

        # train/infer mismatch KL loss (optional)
        # Use train log_probs (has grad) to match infer_log_probs (fixed from rollout).
        if infer_log_probs is not None and (
            getattr(self.pipeline_config, "use_mismatch_forward_kl_loss", False)
            or getattr(self.pipeline_config, "use_mismatch_reverse_kl_loss", False)
        ):
            logp_train = log_probs
            logp_infer = infer_log_probs.detach()

            if getattr(self.pipeline_config, "use_mismatch_forward_kl_loss", False):
                # KL(infer || train) = E_{a~infer} [log p_infer(a) - log p_train(a)]
                mismatch_forward_kl_loss = agg_loss(
                    loss_mat=(logp_infer - logp_train),
                    loss_mask=final_response_mask,
                    loss_agg_mode=self.pipeline_config.loss_agg_mode,
                    loss_scale=loss_scale,
                )
                mismatch_forward_kl_value = mismatch_forward_kl_loss.detach().item()

            if getattr(self.pipeline_config, "use_mismatch_reverse_kl_loss", False):
                # KL(train || infer) = E_{a~train}[log p_train(a) - log p_infer(a)]
                # Approx with IS from infer samples: E_{a~infer}[ r(a) * (log p_train(a) - log p_infer(a)) ],
                # where r = p_train / p_infer.
                _r = (logp_train - logp_infer).exp()
                _r_low = getattr(self.pipeline_config, "mismatch_kl_is_ratio_clip_low", 0.0)
                _r_high = getattr(self.pipeline_config, "mismatch_kl_is_ratio_clip_high", 10.0)
                r = _r.clamp(min=_r_low) if _r_high is None else _r.clamp(_r_low, _r_high)
                mismatch_reverse_kl_loss = agg_loss(
                    loss_mat=r * (logp_train - logp_infer),
                    loss_mask=final_response_mask,
                    loss_agg_mode=self.pipeline_config.loss_agg_mode,
                    loss_scale=loss_scale,
                )
                mismatch_reverse_kl_value = mismatch_reverse_kl_loss.detach().item()

            if getattr(self.pipeline_config, "mismatch_kl_loss_coef", 0.0) > 0:
                if mismatch_reverse_kl_loss is not None:
                    total_loss = total_loss + mismatch_reverse_kl_loss * self.pipeline_config.mismatch_kl_loss_coef
                if mismatch_forward_kl_loss is not None:
                    total_loss = total_loss + mismatch_forward_kl_loss * self.pipeline_config.mismatch_kl_loss_coef

        total_loss = total_loss * self.pipeline_config.rl_loss_coef

        if self.pipeline_config.entropy_loss_coef > 0:
            entropy = self.strategy.op_compute_entropy(logits=output_tensor, attention_mask=data.batch["response_mask"])
            entropy_loss = agg_loss(
                loss_mat=entropy,
                loss_mask=data.batch["response_mask"][:, 1:],
                loss_agg_mode=self.pipeline_config.loss_agg_mode,
                loss_scale=loss_scale
            )
            total_loss = total_loss - entropy_loss * self.pipeline_config.entropy_loss_coef

        metrics = {}
        if self.pipeline_config.postive_loss_coef > 0:
            response_positive_mask = (data.batch['scores'] > 0).unsqueeze(-1).expand_as(final_response_mask)
            # TODO: 是否应该乘上adv？
            postive_loss = agg_loss(loss_mat=-log_probs * advantages, loss_mask=final_response_mask * response_positive_mask,
                                loss_agg_mode=self.pipeline_config.loss_agg_mode, weights=torch.ones_like(sample_weights),
                                loss_scale=loss_scale)
            total_loss = total_loss + postive_loss * self.pipeline_config.postive_loss_coef
            metrics['actor/postive_loss'] = postive_loss.detach().item()

        if self.pipeline_config.use_topr_neg_loss_coef > 0:
            response_negative_mask = (data.batch['scores'] <= 0).unsqueeze(-1).expand_as(final_response_mask)
            clipped_ratio = torch.clamp((log_probs.detach() - is_base_log_probs).exp(), 0 , 1)
            topr_neg_loss = agg_loss(loss_mat=-clipped_ratio * log_probs * advantages, loss_mask=final_response_mask * response_negative_mask,
                                loss_agg_mode=self.pipeline_config.loss_agg_mode, weights=torch.ones_like(sample_weights),
                                loss_scale=loss_scale)
            total_loss = total_loss + topr_neg_loss * self.pipeline_config.use_topr_neg_loss_coef
            metrics['actor/topr_neg_loss'] = topr_neg_loss.detach().item()

        train_infer_prob_metric = {
            "actor/train_infer_ratio_mean": masked_mean(train_infer_ratio, response_mask, dim=-1).mean().detach().item(),
            "actor/train_infer_diff_mean": masked_mean(train_infer_diff, response_mask, dim=-1).mean().detach().item(),
            "actor/train_infer_ratio_mask_mean": train_infer_ratio_mask_mean,
            "actor/train_infer_diff_mask_mean": train_infer_diff_mask_mean,
            "actor/train_infer_ratio_seq_geo_mask_mean": train_infer_ratio_seq_geo_mask_mean,
            "actor/train_infer_ratio_seq_product_mask_mean": train_infer_ratio_seq_product_mask_mean,
            "actor/train_infer_diff_seq_mask_mean": train_infer_diff_seq_mask_mean,
            "actor/train_infer_ratio_trunc_is_weight_mean": train_infer_ratio_trunc_is_weight_mean,
            "actor/train_infer_ratio_trunc_is_weight_max": train_infer_ratio_trunc_is_weight_max,
            "actor/train_infer_ratio_trunc_is_weight_min": train_infer_ratio_trunc_is_weight_min,
            "actor/train_infer_ratio_trunc_reverse_is_weight_mean": train_infer_ratio_trunc_reverse_is_weight_mean,
            "actor/train_infer_ratio_trunc_reverse_is_weight_max": train_infer_ratio_trunc_reverse_is_weight_max,
            "actor/train_infer_ratio_trunc_reverse_is_weight_min": train_infer_ratio_trunc_reverse_is_weight_min,
        }

        loss_metric = {
            "actor/ppo_ratio_high_clipfrac": clipped_high.mean().detach().item(),
            "actor/ppo_ratio_low_clipfrac": clipped_low.mean().detach().item(),
            "actor/ppo_ratio_clipfrac": clipped.mean().detach().item(),
            "actor/ratio_mean": masked_mean(ratio, response_mask, dim=-1).mean().detach().item(),
            "actor/ratio_max": torch.max(ratio * response_mask).detach().item(),
            "actor/ratio_min": torch.min(ratio * response_mask + (1 - response_mask) * 1e10).detach().item(),
            "actor/clipfrac": agg_loss(loss_mat=torch.lt(surr2, surr1).float(), loss_mask=response_mask,
                                loss_agg_mode=self.pipeline_config.loss_agg_mode, loss_scale=loss_scale).detach().item(),
        }


        # Pre-compute token-level Welford stats for cross-batch var aggregation
        _token_valid_mask = response_mask.bool()
        _token_valid_ratios = train_infer_ratio[_token_valid_mask]
        _token_ratio_n = float(_token_valid_ratios.numel())
        _token_ratio_sum = float(_token_valid_ratios.sum().detach().item()) if _token_ratio_n > 0 else 0.0
        _token_ratio_sum_sq = float((_token_valid_ratios ** 2).sum().detach().item()) if _token_ratio_n > 0 else 0.0

        mismatch_metric = {
            #token-level diff and ratio
            "mismatch/train_infer_ratio_mean": masked_mean(train_infer_ratio, response_mask, dim=-1).mean().detach().item(),
            "mismatch/infer_train_ratio_mean": masked_mean(infer_train_ratio, response_mask, dim=-1).mean().detach().item(),
            "mismatch/train_infer_ratio_max": torch.max(train_infer_ratio * response_mask).detach().item(),
            "mismatch/train_infer_ratio_min": torch.min(train_infer_ratio * response_mask + (1 - response_mask) * 1e10).detach().item(),
            "mismatch/train_infer_diff_mean": masked_mean(train_infer_diff, response_mask, dim=-1).mean().detach().item(),
            "mismatch/train_infer_diff_abs_mean": masked_mean(train_infer_diff.abs(), response_mask, dim=-1).mean().detach().item(),
            "mismatch/train_infer_diff_max": torch.max(train_infer_diff * response_mask + (1 - response_mask) * -1e10).detach().item(),
            "mismatch/train_infer_diff_min": torch.min(train_infer_diff * response_mask + (1 - response_mask) * 1e10).detach().item(),
            # Δ(π̄₂, π₂) = E_{q~D, y_i~d^{π̄₂}} [A^{π₂}(s, a)]
            # 其中 π̄₂ 对应 infer_log_probs，π₂ 对应 old_log_probs
            # 使用重要性采样: E_{π̄₂}[A^{π₂}] = E_{π₂}[r * A^{π₂}]，其中 r = π̄₂/π₂
            "mismatch/infer_train_ratio_mean": masked_mean(infer_train_ratio, response_mask, dim=-1).mean().detach().item(),
            "mismatch/infer_train_ratio_max": torch.max(infer_train_ratio * response_mask).detach().item(),
            "mismatch/infer_train_ratio_min": torch.min(infer_train_ratio * response_mask + (1 - response_mask) * 1e10).detach().item(),
            "mismatch/delta_pi2_bar_pi2_mean": masked_mean(delta_pi2_bar_pi2, response_mask, dim=-1).mean().detach().item(),
            "mismatch/delta_pi2_bar_pi2_max": torch.max(delta_pi2_bar_pi2 * response_mask + (1 - response_mask) * -1e10).detach().item(),
            "mismatch/delta_pi2_bar_pi2_min": torch.min(delta_pi2_bar_pi2 * response_mask + (1 - response_mask) * 1e10).detach().item(),
            # token-level ratio: Welford stats for cross-batch var aggregation
            "mismatch/train_infer_ratio_token_n": _token_ratio_n,
            "mismatch/train_infer_ratio_token_sum": _token_ratio_sum,
            "mismatch/train_infer_ratio_token_sum_sq": _token_ratio_sum_sq,
            # seq-level ratio: sequence (product over tokens) = exp(sum(log π/π̄))
            "mismatch/train_infer_ratio_seq_mean": train_infer_ratio_seq_values.mean().detach().item(),
            "mismatch/train_infer_ratio_seq_median": train_infer_ratio_seq_values.median().detach().item(),
            # Welford stats for seq ratio var (cross-batch aggregation)
            "mismatch/train_infer_ratio_seq_n": float(train_infer_ratio_seq_values.numel()),
            "mismatch/train_infer_ratio_seq_sum": float(train_infer_ratio_seq_values.sum().detach().item()),
            "mismatch/train_infer_ratio_seq_sum_sq": float((train_infer_ratio_seq_values ** 2).sum().detach().item()),
            "mismatch/train_infer_ratio_seq_max": train_infer_ratio_seq_values.max().detach().item(),
            "mismatch/train_infer_ratio_seq_min": train_infer_ratio_seq_values.min().detach().item(),
            # seq_geo-level ratio: geometric (mean of log then exp) = exp(mean(log π/π̄))
            "mismatch/train_infer_ratio_seq_geo_mean": train_infer_ratio_seq_geo_values.mean().detach().item(),
            "mismatch/train_infer_ratio_seq_geo_median": train_infer_ratio_seq_geo_values.median().detach().item(),
            # Welford stats for seq_geo ratio var (cross-batch aggregation)
            "mismatch/train_infer_ratio_seq_geo_n": float(train_infer_ratio_seq_geo_values.numel()),
            "mismatch/train_infer_ratio_seq_geo_sum": float(train_infer_ratio_seq_geo_values.sum().detach().item()),
            "mismatch/train_infer_ratio_seq_geo_sum_sq": float((train_infer_ratio_seq_geo_values ** 2).sum().detach().item()),
            "mismatch/train_infer_ratio_seq_geo_max": train_infer_ratio_seq_geo_values.max().detach().item(),
            "mismatch/train_infer_ratio_seq_geo_min": train_infer_ratio_seq_geo_values.min().detach().item(),
            "mismatch/train_infer_diff_seq_mean": train_infer_diff_seq_values.mean().detach().item(),
            "mismatch/train_infer_ratio_mask_mean": train_infer_ratio_mask_mean,
            "mismatch/train_infer_diff_mask_mean": train_infer_diff_mask_mean,
            "mismatch/train_infer_ratio_seq_geo_mask_mean": train_infer_ratio_seq_geo_mask_mean,
            "mismatch/train_infer_ratio_seq_product_mask_mean": train_infer_ratio_seq_product_mask_mean,
            "mismatch/train_infer_diff_seq_mask_mean": train_infer_diff_seq_mask_mean,
            # PPL metrics
            "mismatch/train_infer_train_ppl": train_ppl.mean().detach().item(),
            "mismatch/train_infer_infer_ppl": infer_ppl.mean().detach().item(),
            "mismatch/train_infer_train_log_ppl": (-mean_log_prob_train).mean().detach().item(),
            "mismatch/train_infer_infer_log_ppl": (-mean_log_prob_infer).mean().detach().item(),
            "mismatch/train_infer_ppl_ratio": ppl_ratio_per_seq.mean().detach().item(),
            "mismatch/train_infer_log_ppl_diff": log_ppl_diff.mean().detach().item(),
            "mismatch/train_infer_log_ppl_abs_diff": log_ppl_diff.abs().mean().detach().item(),
            "mismatch/train_infer_log_ppl_diff_max": log_ppl_diff.max().detach().item(),
            "mismatch/train_infer_log_ppl_diff_min": log_ppl_diff.min().detach().item(),
            # KL metrics
            "mismatch/infer_train_kl": agg_loss(loss_mat=infer_train_kl, loss_mask=response_mask,
                                             loss_agg_mode=self.pipeline_config.loss_agg_mode).detach().item(),
            "mismatch/infer_train_k3_kl": agg_loss(loss_mat=infer_train_k3_kl, loss_mask=response_mask,
                                                loss_agg_mode=self.pipeline_config.loss_agg_mode).detach().item(),
            # TODO: 以下指标需要根据实际需求实现
            # "mismatch/ess": ess.detach().item() if 'ess' in locals() else 0.0,
            # "mismatch/pos_adv_frac": pos_adv_frac.detach().item() if 'pos_adv_frac' in locals() else 0.0,
            # "mismatch/update_efficiency": efficiency_metric.detach().item() if 'efficiency_metric' in locals() else 0.0,
        }

        # ===== mismatch extra stats: correct/incorrect, buckets, percentiles =====
        # sequence-level mismatch values (one scalar per sample)
        seq_mismatch_values = {
            "train_infer_ratio_seq_geo": train_infer_ratio_seq_geo_values,
            "train_infer_ratio": masked_mean(train_infer_ratio, response_mask, dim=-1),
            "train_infer_diff": masked_mean(train_infer_diff, response_mask, dim=-1),
            "train_infer_diff_abs": masked_mean(train_infer_diff.abs(), response_mask, dim=-1),
            "infer_train_kl": masked_mean(infer_train_kl, response_mask, dim=-1),
            "infer_train_k3_kl": masked_mean(infer_train_k3_kl, response_mask, dim=-1),
            "train_infer_train_ppl": train_ppl,
            "train_infer_infer_ppl": infer_ppl,
        }
        correct_mask = data.batch["scores"] > 0
        incorrect_mask = ~correct_mask

        def _safe_masked_mean(values: torch.Tensor, mask: torch.Tensor) -> float:
            if values.numel() == 0:
                return 0.0
            valid = values[mask]
            if valid.numel() == 0:
                return 0.0
            return valid.float().mean().detach().item()

        # (1) correct / incorrect mismatch stats
        mismatch_metric["mismatch/correct/sample_n"] = float(correct_mask.sum().detach().item())
        mismatch_metric["mismatch/incorrect/sample_n"] = float(incorrect_mask.sum().detach().item())
        for metric_name, metric_values in seq_mismatch_values.items():
            mismatch_metric[f"mismatch/correct/{metric_name}_mean"] = _safe_masked_mean(metric_values, correct_mask)
            mismatch_metric[f"mismatch/incorrect/{metric_name}_mean"] = _safe_masked_mean(metric_values, incorrect_mask)

        # (2) low/mid/high buckets for selected mismatch metrics
        bucket_metrics = [
            "train_infer_ratio_seq_geo",
            "train_infer_ratio",
            "train_infer_diff",
            "train_infer_diff_abs",
        ]
        for metric_name in bucket_metrics:
            metric_values = seq_mismatch_values[metric_name].float()
            if metric_values.numel() == 0:
                for bucket_name in ("low", "mid", "high"):
                    mismatch_metric[f"mismatch/bucket/{metric_name}/{bucket_name}_mean"] = 0.0
                    mismatch_metric[f"mismatch/bucket/{metric_name}/{bucket_name}_n"] = 0.0
                continue

            q_low, q_high = torch.quantile(
                metric_values,
                torch.tensor([1.0 / 3.0, 2.0 / 3.0], device=metric_values.device),
            )
            low_mask = metric_values <= q_low
            mid_mask = (metric_values > q_low) & (metric_values <= q_high)
            high_mask = metric_values > q_high
            bucket_def = {"low": low_mask, "mid": mid_mask, "high": high_mask}
            for bucket_name, bucket_mask in bucket_def.items():
                mismatch_metric[f"mismatch/bucket/{metric_name}/{bucket_name}_mean"] = _safe_masked_mean(
                    metric_values, bucket_mask
                )
                mismatch_metric[f"mismatch/bucket/{metric_name}/{bucket_name}_n"] = float(
                    bucket_mask.sum().detach().item()
                )

        # (3) mismatch percentiles
        percentile_list = [95, 90, 85, 80, 75, 70, 10, 20, 30, 40]
        for metric_name, metric_values in seq_mismatch_values.items():
            metric_values = metric_values.float()
            if metric_values.numel() == 0:
                for p in percentile_list:
                    mismatch_metric[f"mismatch/percentile/{metric_name}_p{p}"] = 0.0
                continue
            for p in percentile_list:
                q = torch.quantile(metric_values, float(p) / 100.0)
                mismatch_metric[f"mismatch/percentile/{metric_name}_p{p}"] = q.detach().item()


        if self.pipeline_config.use_rollout_importance_sampling_ratio:
            loss_metric["actor/rollout_importance_sampling_clip"] = rollout_importance_sampling_clip.mean().detach().item()

        pg_metrics = {
            "actor/pg_loss": original_pg_loss.detach().item(),
            "actor/weighted_pg_loss": weighted_pg_loss.detach().item(),
            "actor/kl_loss": kl_loss.detach().item(),
            "actor/total_loss": total_loss.detach().item(),
            "actor/mismatch_forward_kl_loss": mismatch_forward_kl_value,
            "actor/mismatch_reverse_kl_loss": mismatch_reverse_kl_value,
            "actor/approxkl": agg_loss(loss_mat=approxkl, loss_mask=response_mask,
                                       loss_agg_mode=self.pipeline_config.loss_agg_mode).detach().item(),
            "actor/policykl": agg_loss(loss_mat=policykl, loss_mask=response_mask,
                                       loss_agg_mode=self.pipeline_config.loss_agg_mode).detach().item(),
            "actor/valid_samples": valid_samples.sum().detach().item(),
            "actor/total_samples": float(valid_samples.size(0)),
            "actor/valid_sample_ratio": (valid_samples.sum() / valid_samples.size(0)).detach().item(),
            "actor/sample_weights_mean": sample_weights.mean().detach().item(),
            "actor/sample_weights_min": sample_weights.min().detach().item(),
            "actor/sample_weights_max": sample_weights.max().detach().item(),
            **metrics,
            **loss_metric,
            **train_infer_prob_metric,
            **mismatch_metric
        }

        # Collect data for train_infer_ratio log dump (both seq and seq_geo per-seq ratios)
        self._collect_ratio_dump_data(
            data, train_infer_ratio_seq_values, train_infer_ratio_seq_geo_values, train_infer_ratio, response_mask
        )

        return total_loss, pg_metrics

    def _collect_ratio_dump_data(self, data, seq_ratios, seq_geo_ratios, token_ratios, response_mask):
        """
        Collect per-micro-batch data for train_infer_ratio log.
        Records both seq ratio (product) and seq_geo ratio (geometric) per sequence.
        For each sequence, eagerly decode prompt/response text and extract top 10 token-level ratios.
        Only lightweight Python objects are stored in the buffer to minimize memory usage.
        """
        if not hasattr(self, '_ratio_dump_buffer') or self._ratio_dump_buffer is None:
            return

        batch_size = seq_ratios.shape[0]

        # Batch CPU transfer to minimize GPU-CPU sync overhead
        seq_ratios_cpu = seq_ratios.detach().cpu()
        seq_geo_ratios_cpu = seq_geo_ratios.detach().cpu()
        token_ratios_cpu = token_ratios.detach().cpu()
        response_mask_cpu = response_mask.detach().cpu()
        input_ids_cpu = data.batch['input_ids'].detach().cpu()
        response_mask_full_cpu = data.batch['response_mask'].detach().cpu()

        prompts = data.non_tensor_batch.get('prompt', [''] * batch_size) if data.non_tensor_batch else [''] * batch_size
        data_ids = data.non_tensor_batch.get('id', [''] * batch_size) if data.non_tensor_batch else [''] * batch_size

        for i in range(batch_size):
            # Decode response text from input_ids using response_mask
            response_tokens = input_ids_cpu[i][response_mask_full_cpu[i].bool()]
            response_text = self.tokenizer.decode(response_tokens, skip_special_tokens=True)

            # Find top 10 tokens by token-level ratio
            t_ratios = token_ratios_cpu[i]       # [seq_len - 1]
            t_mask = response_mask_cpu[i]         # [seq_len - 1]
            valid_indices = t_mask.nonzero(as_tuple=True)[0]

            top_tokens = []
            if len(valid_indices) > 0:
                valid_ratios = t_ratios[valid_indices]
                top_k = min(10, len(valid_ratios))
                top_values, top_local_indices = valid_ratios.topk(top_k)
                top_global_indices = valid_indices[top_local_indices]

                for j in range(top_k):
                    pos = top_global_indices[j].item()
                    # Position pos in token_ratios corresponds to input_ids[pos + 1]
                    token_id = input_ids_cpu[i][pos + 1].item()
                    token_text = self.tokenizer.decode([token_id])
                    top_tokens.append({
                        'position': int(pos),
                        'token_id': int(token_id),
                        'token_text': token_text,
                        'token_ratio': round(top_values[j].item(), 6)
                    })

            # Collect all valid token-level ratios for token-level dump
            all_token_ratios = []
            seq_token_mean_ratio = 0.0
            if len(valid_indices) > 0:
                all_valid_ratios = t_ratios[valid_indices]
                seq_token_mean_ratio = round(all_valid_ratios.float().mean().item(), 6)
                if getattr(self.pipeline_config, "ratio_dump_include_token_ratios", True):
                    all_token_ratios = [round(r.item(), 6) for r in all_valid_ratios]

            self._ratio_dump_buffer.append({
                'global_step': int(data.meta_info.get('global_step', 0)),
                'worker_name': str(self.worker_name),
                'rank': int(getattr(self, 'rank', 0)),
                'dp_rank': int(getattr(getattr(self, 'rank_info', None), 'dp_rank', 0)),
                'data_id': str(data_ids[i]) if i < len(data_ids) else '',
                'seq_ratio': round(seq_ratios_cpu[i].item(), 6),
                'seq_geo_ratio': round(seq_geo_ratios_cpu[i].item(), 6),
                'seq_token_mean_ratio': seq_token_mean_ratio,
                'prompt': str(prompts[i]) if i < len(prompts) else '',
                'response': response_text,
                'top_10_token_ratios': top_tokens,
                'all_token_ratios': all_token_ratios,
            })

    def _dump_ratio_buffer(self, dump_path: str, global_step: int, records):
        os.makedirs(dump_path, exist_ok=True)
        worker = str(self.worker_name or "actor_train").replace("/", "_")
        filename = f"tis_is.step_{int(global_step):06d}.{worker}.rank_{int(getattr(self, 'rank', 0)):05d}.{int(time.time() * 1000)}.jsonl"
        output_path = os.path.join(dump_path, filename)
        try:
            with open(output_path, "w", encoding="utf-8") as f:
                for record in records:
                    f.write(json.dumps(record, ensure_ascii=False) + "\n")
            _ratio_log_logger.info(f"dumped TIS IS ratio records to {output_path}, n={len(records)}")
        except Exception as exc:
            _ratio_log_logger.warning(f"failed to dump TIS IS ratio records to {output_path}: {exc}")

